package app.trailplan.routing;

import java.math.BigDecimal;
import java.util.Set;
import java.util.StringJoiner;
import java.util.stream.Collectors;
import java.util.stream.IntStream;
import java.util.stream.Stream;

/**
 * Turns {@link RoutingPreferences} into a BRouter profile (.brf). Cost factors scale the per-metre
 * cost of a way; 10000 makes a way effectively impassable.
 */
public final class BRouterProfileGenerator {

  private static final String BLOCKED = "10000";

  /** Cost of a closed or restricted way on a forced leg: used only where nothing else fits. */
  private static final String FORCED_COST = "8";

  /**
   * mtb:scale values known to BRouter's lookup table (misc/profiles2/lookups.dat). BRouter rejects
   * profiles that mention unknown values, so only these may appear in the profile.
   */
  private static final Set<String> MTB_SCALE_VALUES =
      Set.of("0", "0-", "0+", "1", "1-", "1+", "2", "2-", "2+", "3", "4", "5", "6");

  /** Surfaces a road bike should not ride (lookups.dat names, aliases resolved by BRouter). */
  private static final String ROAD_ROUGH_SURFACE =
      "surface=unpaved|gravel|ground|dirt|grass|sand|mud|pebblestone|earth|clay|rock|stone"
          + "|grass_paver";

  /**
   * Other signs of a way a road bike cannot ride: bad smoothness, and tracks with neither a surface
   * nor a solid grade.
   */
  private static final String ROAD_ROUGH_OTHER =
      "or smoothness=bad|very_bad|horrible|very_horrible|impassable|off_road_wheels"
          + " and highway=track and surface= not tracktype=grade1";

  /** Mountain paths too steep or exposed for a horse. */
  private static final String HORSE_TOO_HARD_SAC =
      "demanding_mountain_hiking|alpine_hiking|demanding_alpine_hiking|difficult_alpine_hiking";

  /** Barriers built to stop horses, or too narrow for one. */
  private static final String HORSE_BARRIERS =
      "stile|turnstile|full-height_turnstile|kissing_gate|horse_stile|motorcycle_barrier"
          + "|cattle_grid";

  public String generate(RoutingPreferences prefs) {
    return generate(prefs, false);
  }

  /**
   * @param forced allow closed and restricted ways (under construction, no access, no bikes or
   *     horses, against a one-way street) at a high cost instead of blocking them; motorways stay
   *     blocked
   */
  public String generate(RoutingPreferences prefs, boolean forced) {
    StringJoiner out = new StringJoiner("\n", "", "\n");
    Activity activity = prefs.activity();

    out.add("# Generated by Trailplan. Do not edit; the file name is a hash of its content.");
    out.add("---context:global");
    out.add("assign validForBikes 1");
    // Report all OSM tags in the result, not only the ones used below (needed for surfaces).
    out.add("assign processUnusedTags 1");
    out.add("assign downhillcost 0");
    out.add("assign downhillcutoff 1.5");
    out.add("assign uphillcost " + (prefs.avoidClimbs() ? "80" : "0"));
    out.add("assign uphillcutoff 1.5");
    out.add("");

    out.add("---context:way");
    out.add("assign turncost 0");
    out.add("assign initialcost 0");
    if (activity == Activity.HORSE) {
      out.add("assign accessno access=no|private");
      // lookups.dat folds permissive into yes and official into designated.
      out.add("assign horseyes horse=yes|designated|destination");
      out.add("assign horseno horse=no|private");
      // Footways and cycleways are not for horses unless tagged so.
      out.add("assign notforhorses and highway=footway|pedestrian|cycleway not horseyes");
      out.add("assign blocked or or horseno notforhorses and accessno not horseyes");
      out.add("assign badoneway and reversedirection=yes oneway=yes|true|1");
    } else {
      out.add("assign bikeyes bicycle=yes|permissive|designated|destination");
      out.add("assign bikeno bicycle=no|private|use_sidepath");
      out.add("assign accessno access=no|private");
      out.add("assign blocked or bikeno and accessno not bikeyes");
      out.add(
          "assign badoneway and reversedirection=yes and oneway=yes|true|1 not oneway:bicycle=no");
    }
    out.add("assign toohard " + tooHardExpression(prefs));
    double outsideForest = prefs.woods().outsideForestFactor();
    out.add(
        outsideForest > 1 && activity != Activity.ROAD
            ? "assign forestmult switch estimated_forest_class=3|4|5|6 1 " + number(outsideForest)
            : "assign forestmult 1");
    switch (activity) {
      case MTB -> {}
      case ROAD -> {
        out.add("assign rough or " + ROAD_ROUGH_SURFACE + " " + ROAD_ROUGH_OTHER);
        out.add("assign surfacemult");
        out.add("  switch rough " + BLOCKED);
        out.add("  switch surface=compacted|fine_gravel 3");
        out.add("  switch surface=cobblestone 2.5");
        out.add("  switch surface=sett 1.5");
        out.add("  1");
        // BRouter's traffic estimate (1 quiet .. 7 very busy): a nudge towards quieter roads.
        out.add("assign trafficmult switch estimated_traffic_class=6|7 1.5");
        out.add("  switch estimated_traffic_class=5 1.25 1");
      }
      case HORSE -> {
        // Soft ground is kinder to hooves; setts and cobbles are slippery.
        out.add("assign surfacemult");
        out.add("  switch surface=sett|cobblestone|paving_stones|metal 1.6");
        out.add("  switch surface=asphalt|concrete|paved 1.3");
        out.add("  1");
      }
    }
    out.add("assign typecost");
    out.add("  switch route=ferry 6");
    if (forced) {
      out.add("  switch highway=construction " + FORCED_COST);
    }
    out.add("  switch highway= " + BLOCKED);
    out.add("  switch highway=motorway|motorway_link " + BLOCKED);
    if (activity == Activity.HORSE) {
      out.add("  switch highway=trunk|trunk_link " + BLOCKED);
      out.add("  switch highway=primary|primary_link " + cost(prefs, WayCategory.BUSY_ROAD));
    } else {
      out.add(
          "  switch highway=trunk|trunk_link|primary|primary_link "
              + cost(prefs, WayCategory.BUSY_ROAD));
    }
    out.add(
        "  switch highway=secondary|secondary_link|tertiary|tertiary_link "
            + cost(prefs, WayCategory.MAIN_ROAD));
    out.add(
        "  switch highway=residential|unclassified|service|living_street|road "
            + cost(prefs, WayCategory.QUIET_ROAD));
    out.add("  switch highway=cycleway " + cost(prefs, WayCategory.CYCLEWAY));
    out.add("  switch highway=footway|pedestrian " + cost(prefs, WayCategory.FOOTWAY));
    if (activity == Activity.ROAD) {
      // Shared foot and cycle paths are tagged as paths with bicycle=designated.
      out.add(
          "  switch highway=path switch bicycle=designated "
              + cost(prefs, WayCategory.CYCLEWAY)
              + " "
              + cost(prefs, WayCategory.TRAIL));
      out.add("  switch highway=bridleway " + cost(prefs, WayCategory.TRAIL));
    } else {
      out.add("  switch highway=path|bridleway " + cost(prefs, WayCategory.TRAIL));
    }
    out.add(
        "  switch highway=track switch tracktype=grade1|grade2 "
            + cost(prefs, WayCategory.GRAVEL_TRACK)
            + " "
            + cost(prefs, WayCategory.ROUGH_TRACK));
    // Steps belong to footways in the breakdown but always cost extra: you carry the bike (a road
    // bike only for a few steps). A horse cannot use them at all.
    out.add(
        "  switch highway=steps "
            + switch (activity) {
              case MTB -> "8";
              case ROAD -> "15";
              case HORSE -> BLOCKED;
            });
    out.add("  " + BLOCKED);
    out.add("assign costfactor");
    out.add("  switch or blocked badoneway " + (forced ? FORCED_COST : BLOCKED));
    out.add("  switch toohard " + BLOCKED);
    out.add(
        switch (activity) {
          case MTB -> "  multiply typecost forestmult";
          case ROAD -> "  multiply multiply typecost surfacemult trafficmult";
          case HORSE -> "  multiply multiply typecost forestmult surfacemult";
        });
    out.add("");

    out.add("---context:node");
    if (activity == Activity.HORSE) {
      // Barriers a horse cannot pass, unless tagged as passable for horses. 1000000 makes BRouter
      // treat the node as impassable.
      out.add(
          "assign initialcost switch and barrier="
              + HORSE_BARRIERS
              + " not horse=yes|designated 1000000 0");
    } else {
      out.add("assign initialcost 0");
    }
    return out.toString();
  }

  private static String tooHardExpression(RoutingPreferences prefs) {
    return switch (prefs.activity()) {
      case MTB -> mtbScaleAbove(prefs.maxDifficulty());
      // Any graded trail is a mountain-bike trail, not a road.
      case ROAD -> "not mtb:scale=";
      case HORSE -> "sac_scale=" + HORSE_TOO_HARD_SAC;
    };
  }

  private static String mtbScaleAbove(TrailDifficulty max) {
    if (max == TrailDifficulty.ANY) {
      return "0";
    }
    String grades =
        IntStream.rangeClosed(max.maxScale() + 1, 6)
            .boxed()
            .flatMap(grade ->
                Stream.of(grade + "-", Integer.toString(grade), grade + "+")
                    .filter(MTB_SCALE_VALUES::contains))
            .collect(Collectors.joining("|"));
    return "mtb:scale=" + grades;
  }

  private static String cost(RoutingPreferences prefs, WayCategory category) {
    return number(prefs.level(category).costFactor());
  }

  private static String number(double value) {
    return BigDecimal.valueOf(value).stripTrailingZeros().toPlainString();
  }
}
