package app.trailplan.routing;

import java.math.BigDecimal;
import java.util.Set;
import java.util.StringJoiner;
import java.util.stream.Collectors;
import java.util.stream.IntStream;
import java.util.stream.Stream;

/**
 * Turns {@link RoutingPreferences} into a BRouter profile (.brf). Cost factors scale the per-metre
 * cost of a way; 10000 makes a way effectively impassable.
 */
public final class BRouterProfileGenerator {

  private static final String BLOCKED = "10000";

  /** Cost of a closed or restricted way on a forced leg: used only where nothing else fits. */
  private static final String FORCED_COST = "8";

  /**
   * mtb:scale values known to BRouter's lookup table (misc/profiles2/lookups.dat). BRouter rejects
   * profiles that mention unknown values, so only these may appear in the profile.
   */
  private static final Set<String> MTB_SCALE_VALUES =
      Set.of("0", "0-", "0+", "1", "1-", "1+", "2", "2-", "2+", "3", "4", "5", "6");

  public String generate(RoutingPreferences prefs) {
    return generate(prefs, false);
  }

  /**
   * @param forced allow closed and restricted ways (under construction, no access, no bikes,
   *     against a one-way street) at a high cost instead of blocking them; motorways stay blocked
   */
  public String generate(RoutingPreferences prefs, boolean forced) {
    StringJoiner out = new StringJoiner("\n", "", "\n");

    out.add("# Generated by Trailplan. Do not edit; the file name is a hash of its content.");
    out.add("---context:global");
    out.add("assign validForBikes 1");
    // Report all OSM tags in the result, not only the ones used below (needed for surfaces).
    out.add("assign processUnusedTags 1");
    out.add("assign downhillcost 0");
    out.add("assign downhillcutoff 1.5");
    out.add("assign uphillcost " + (prefs.avoidClimbs() ? "80" : "0"));
    out.add("assign uphillcutoff 1.5");
    out.add("");

    out.add("---context:way");
    out.add("assign turncost 0");
    out.add("assign initialcost 0");
    out.add("assign bikeyes bicycle=yes|permissive|designated|destination");
    out.add("assign bikeno bicycle=no|private|use_sidepath");
    out.add("assign accessno access=no|private");
    out.add("assign blocked or bikeno and accessno not bikeyes");
    out.add(
        "assign badoneway and reversedirection=yes and oneway=yes|true|1 not oneway:bicycle=no");
    out.add("assign toohard " + tooHardExpression(prefs.maxDifficulty()));
    double outsideForest = prefs.woods().outsideForestFactor();
    out.add(
        outsideForest > 1
            ? "assign forestmult switch estimated_forest_class=3|4|5|6 1 " + number(outsideForest)
            : "assign forestmult 1");
    out.add("assign typecost");
    out.add("  switch route=ferry 6");
    if (forced) {
      out.add("  switch highway=construction " + FORCED_COST);
    }
    out.add("  switch highway= " + BLOCKED);
    out.add("  switch highway=motorway|motorway_link " + BLOCKED);
    out.add(
        "  switch highway=trunk|trunk_link|primary|primary_link "
            + cost(prefs, WayCategory.BUSY_ROAD));
    out.add(
        "  switch highway=secondary|secondary_link|tertiary|tertiary_link "
            + cost(prefs, WayCategory.MAIN_ROAD));
    out.add(
        "  switch highway=residential|unclassified|service|living_street|road "
            + cost(prefs, WayCategory.QUIET_ROAD));
    out.add("  switch highway=cycleway " + cost(prefs, WayCategory.CYCLEWAY));
    out.add("  switch highway=footway|pedestrian " + cost(prefs, WayCategory.FOOTWAY));
    out.add("  switch highway=path|bridleway " + cost(prefs, WayCategory.TRAIL));
    out.add(
        "  switch highway=track switch tracktype=grade1|grade2 "
            + cost(prefs, WayCategory.GRAVEL_TRACK)
            + " "
            + cost(prefs, WayCategory.ROUGH_TRACK));
    // Steps belong to footways in the breakdown but always cost extra: you carry the bike.
    out.add("  switch highway=steps 8");
    out.add("  " + BLOCKED);
    out.add("assign costfactor");
    out.add("  switch or blocked badoneway " + (forced ? FORCED_COST : BLOCKED));
    out.add("  switch toohard " + BLOCKED);
    out.add("  multiply typecost forestmult");
    out.add("");

    out.add("---context:node");
    out.add("assign initialcost 0");
    return out.toString();
  }

  private static String tooHardExpression(TrailDifficulty max) {
    if (max == TrailDifficulty.ANY) {
      return "0";
    }
    String grades =
        IntStream.rangeClosed(max.maxScale() + 1, 6)
            .boxed()
            .flatMap(grade ->
                Stream.of(grade + "-", Integer.toString(grade), grade + "+")
                    .filter(MTB_SCALE_VALUES::contains))
            .collect(Collectors.joining("|"));
    return "mtb:scale=" + grades;
  }

  private static String cost(RoutingPreferences prefs, WayCategory category) {
    return number(prefs.level(category).costFactor());
  }

  private static String number(double value) {
    return BigDecimal.valueOf(value).stripTrailingZeros().toPlainString();
  }
}
